const dictionaries: Record<Language, Record<MessageKey, string>> = { en, 'zh-TW': zhTW }

export function t(lang: Language, key: MessageKey, vars?: Record<string, string | number>): string {
  let s = dictionaries[lang][key] ?? en[key]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}

/** 1h 30m / 1小時30分. Rounds to whole minutes. */
export function formatDuration(lang: Language, ms: number): string {
  const total = Math.round(ms / 60_000)
  const h = Math.floor(total / 60)
  const m = total % 60
  if (lang === 'zh-TW') return h ? (m ? `${h}小時${m}分` : `${h}小時`) : `${m}分`
  return h ? (m ? `${h}h ${m}m` : `${h}h`) : `${m}m`
}

/** Short hour value for chart axes: 1.5h / 1.5小時 */
export function formatHours(lang: Language, ms: number): string {
  const h = Math.round((ms / 3_600_000) * 10) / 10
  return lang === 'zh-TW' ? `${h}小時` : `${h}h`
}

export function locale(lang: Language): string {
  return lang === 'zh-TW' ? 'zh-TW' : 'en-US'
}
